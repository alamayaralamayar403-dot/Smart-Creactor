/**
 * دالة البحث في الأوامر
 */
export function searchPrompts(query: string): Prompt[] {
  const lowerQuery = query.toLowerCase();
  return PROMPTS_LIBRARY.filter(
    (prompt) =>
      prompt.title.toLowerCase().includes(lowerQuery) ||
      prompt.description.toLowerCase().includes(lowerQuery) ||
      prompt.tags.some((tag) => tag.toLowerCase().includes(lowerQuery))
  );
}

/**
 * دالة الحصول على الأوامر حسب الفئة
 */
export function getPromptsByCategory(category: Prompt['category']): Prompt[] {
  return PROMPTS_LIBRARY.filter((prompt) => prompt.category === category);
}

/**
 * دالة الحصول على الأوامر حسب مستوى الصعوبة
 */
export function getPromptsByDifficulty(difficulty: Prompt['difficulty']): Prompt[] {
  return PROMPTS_LIBRARY.filter((prompt) => prompt.difficulty === difficulty);
}

/**
 * دالة الحصول على أمر عشوائي
 */
export function getRandomPrompt(): Prompt {
  return PROMPTS_LIBRARY[Math.floor(Math.random() * PROMPTS_LIBRARY.length)];
}

/**
 * دالة الحصول على إحصائيات الأوامر
 */
export function getPromptsStats() {
  const categories = new Set(PROMPTS_LIBRARY.map((p) => p.category));
  const difficulties = new Set(PROMPTS_LIBRARY.map((p) => p.difficulty));

  return {
    totalPrompts: PROMPTS_LIBRARY.length,
    categories: Array.from(categories),
    difficulties: Array.from(difficulties),
    byCategory: Object.fromEntries(
      Array.from(categories).map((cat) => [
        cat,
        PROMPTS_LIBRARY.filter((p) => p.category === cat).length,
      ])
    ),
  };
}
